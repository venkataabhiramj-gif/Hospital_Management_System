CREATE TABLE prescription_substitution_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_item_id BIGINT NOT NULL REFERENCES prescription_items(id),
    original_medicine_id BIGINT NOT NULL REFERENCES medicines(id),
    substitute_medicine_id BIGINT NOT NULL REFERENCES medicines(id),
    approved_by BIGINT NOT NULL REFERENCES staff_users(id),
    reason VARCHAR(500) NOT NULL,
    approved_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_prescription_substitutions_item_time
    ON prescription_substitution_history (prescription_item_id, approved_at);
