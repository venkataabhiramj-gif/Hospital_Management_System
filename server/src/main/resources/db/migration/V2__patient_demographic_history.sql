CREATE TABLE patient_demographic_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    changed_by BIGINT NOT NULL REFERENCES staff_users(id),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    old_full_name VARCHAR(200) NOT NULL,
    new_full_name VARCHAR(200) NOT NULL,
    old_date_of_birth DATE,
    new_date_of_birth DATE,
    old_phone VARCHAR(32),
    new_phone VARCHAR(32),
    correction_reason VARCHAR(500) NOT NULL
);

CREATE INDEX ix_patient_demographic_history_patient_time
    ON patient_demographic_history (patient_id, changed_at);
