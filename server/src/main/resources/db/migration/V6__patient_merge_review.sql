ALTER TABLE patients
    ADD COLUMN merged_into_patient_id BIGINT REFERENCES patients(id);

ALTER TABLE patients
    ADD CONSTRAINT ck_patients_not_merged_into_self
    CHECK (merged_into_patient_id IS NULL OR merged_into_patient_id <> id);

CREATE INDEX ix_patients_merged_into ON patients (merged_into_patient_id);

CREATE TABLE patient_merge_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_patient_id BIGINT NOT NULL REFERENCES patients(id),
    target_patient_id BIGINT NOT NULL REFERENCES patients(id),
    source_patient_number VARCHAR(24) NOT NULL,
    target_patient_number VARCHAR(24) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    merged_by BIGINT NOT NULL REFERENCES staff_users(id),
    merged_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (source_patient_id <> target_patient_id)
);

CREATE INDEX ix_patient_merge_history_source ON patient_merge_history (source_patient_id, merged_at);
CREATE INDEX ix_patient_merge_history_target ON patient_merge_history (target_patient_id, merged_at);
