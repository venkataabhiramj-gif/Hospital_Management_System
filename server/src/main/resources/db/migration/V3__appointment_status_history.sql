CREATE TABLE appointment_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES appointments(id),
    previous_status VARCHAR(24),
    new_status VARCHAR(24) NOT NULL,
    reason VARCHAR(500),
    changed_by BIGINT NOT NULL REFERENCES staff_users(id),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_appointment_status_history_appointment_time
    ON appointment_status_history (appointment_id, changed_at);

INSERT INTO appointment_status_history (appointment_id, previous_status, new_status, reason, changed_by, changed_at)
