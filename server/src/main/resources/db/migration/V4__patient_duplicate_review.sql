CREATE TABLE patient_duplicate_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    new_patient_id BIGINT NOT NULL REFERENCES patients(id),
    possible_match_patient_id BIGINT NOT NULL REFERENCES patients(id),
    match_signals VARCHAR(160) NOT NULL,
    review_reason VARCHAR(500) NOT NULL,
    reviewed_by BIGINT NOT NULL REFERENCES staff_users(id),
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_patient_duplicate_reviews_new_patient
    ON patient_duplicate_reviews (new_patient_id, reviewed_at);

CREATE INDEX ix_patient_duplicate_reviews_candidate
    ON patient_duplicate_reviews (possible_match_patient_id, reviewed_at);
