CREATE TABLE staff_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('ADMIN', 'RECEPTIONIST', 'DOCTOR', 'PHARMACIST', 'BILLING')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_number VARCHAR(24) NOT NULL UNIQUE,
    full_name VARCHAR(200) NOT NULL,
    date_of_birth DATE,
    phone VARCHAR(32),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_patients_name ON patients (full_name);
CREATE INDEX ix_patients_phone ON patients (phone);

CREATE TABLE doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_user_id BIGINT NOT NULL UNIQUE REFERENCES staff_users(id),
    specialty VARCHAR(120) NOT NULL,
    appointment_minutes INTEGER NOT NULL DEFAULT 20 CHECK (appointment_minutes BETWEEN 5 AND 240),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE doctor_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    visit_type VARCHAR(24) NOT NULL CHECK (visit_type IN ('APPOINTMENT', 'WALK_IN')),
    status VARCHAR(24) NOT NULL CHECK (status IN ('BOOKED', 'CHECKED_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    reason VARCHAR(500),
    booked_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (ends_at > starts_at)
);

CREATE INDEX ix_appointments_doctor_time ON appointments (doctor_id, starts_at, ends_at);
CREATE INDEX ix_appointments_patient_time ON appointments (patient_id, starts_at);

CREATE TABLE encounters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    complaint VARCHAR(1000),
    blood_pressure VARCHAR(20),
    pulse_per_minute INTEGER CHECK (pulse_per_minute BETWEEN 0 AND 300),
    temperature_celsius DECIMAL(4, 1) CHECK (temperature_celsius BETWEEN 20 AND 50),
    weight_kg DECIMAL(6, 2) CHECK (weight_kg BETWEEN 0 AND 1000),
    allergies TEXT,
    current_medicines TEXT,
    clinical_notes TEXT,
    diagnosis_text VARCHAR(1000),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN', 'FINALIZED')),
    created_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalized_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE encounter_addenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES encounters(id),
    correction_reason VARCHAR(500) NOT NULL,
    addendum_text TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE medicines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    generic_name VARCHAR(200) NOT NULL,
    brand_name VARCHAR(200),
    strength VARCHAR(80),
    dosage_form VARCHAR(80),
    unit VARCHAR(40) NOT NULL,
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    sale_price DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_medicines_name ON medicines (generic_name);

CREATE TABLE medicine_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id BIGINT NOT NULL REFERENCES medicines(id),
    batch_number VARCHAR(100) NOT NULL,
    expiry_date DATE NOT NULL,
    supplier VARCHAR(200),
    purchase_price DECIMAL(12, 2) NOT NULL CHECK (purchase_price >= 0),
    quantity_on_hand INTEGER NOT NULL CHECK (quantity_on_hand >= 0),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    received_by BIGINT NOT NULL REFERENCES staff_users(id),
    UNIQUE (medicine_id, batch_number)
);

CREATE INDEX ix_medicine_batches_expiry ON medicine_batches (medicine_id, expiry_date);

CREATE TABLE prescriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL REFERENCES encounters(id),
    prescribed_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL REFERENCES prescriptions(id),
    medicine_id BIGINT NOT NULL REFERENCES medicines(id),
    dosage VARCHAR(120) NOT NULL,
    route VARCHAR(80),
    frequency VARCHAR(120) NOT NULL,
    duration_days INTEGER CHECK (duration_days IS NULL OR duration_days BETWEEN 1 AND 3650),
    quantity_prescribed INTEGER NOT NULL CHECK (quantity_prescribed > 0),
    instructions VARCHAR(1000),
    substitution_approved_by BIGINT REFERENCES staff_users(id)
);

CREATE TABLE dispensings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_item_id BIGINT NOT NULL REFERENCES prescription_items(id),
    batch_id BIGINT NOT NULL REFERENCES medicine_batches(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    dispensed_by BIGINT NOT NULL REFERENCES staff_users(id),
    dispensed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id BIGINT NOT NULL REFERENCES medicines(id),
    batch_id BIGINT NOT NULL REFERENCES medicine_batches(id),
    movement_type VARCHAR(24) NOT NULL CHECK (movement_type IN ('RECEIVED', 'DISPENSED', 'RETURNED', 'ADJUSTED')),
    quantity_change INTEGER NOT NULL CHECK (quantity_change <> 0),
    reason VARCHAR(500),
    reference_type VARCHAR(32),
    reference_id BIGINT,
    created_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_stock_movements_batch_time ON stock_movements (batch_id, created_at);

CREATE TABLE service_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL CHECK (unit_price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(32) NOT NULL UNIQUE,
    encounter_id BIGINT NOT NULL UNIQUE REFERENCES encounters(id),
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    status VARCHAR(24) NOT NULL CHECK (status IN ('OPEN', 'PARTIALLY_PAID', 'PAID', 'VOID')),
    created_by BIGINT NOT NULL REFERENCES staff_users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    void_reason VARCHAR(500),
    voided_by BIGINT REFERENCES staff_users(id),
    voided_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    item_type VARCHAR(24) NOT NULL CHECK (item_type IN ('SERVICE', 'MEDICINE')),
    description_snapshot VARCHAR(240) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_snapshot DECIMAL(12, 2) NOT NULL CHECK (unit_price_snapshot >= 0),
    source_id BIGINT
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number VARCHAR(32) NOT NULL UNIQUE,
    invoice_id BIGINT NOT NULL REFERENCES invoices(id),
    amount DECIMAL(12, 2) NOT NULL CHECK (amount > 0),
    method VARCHAR(24) NOT NULL CHECK (method IN ('CASH', 'UPI', 'CARD', 'BANK_TRANSFER', 'OTHER')),
    received_by BIGINT NOT NULL REFERENCES staff_users(id),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    refund_amount DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0 AND refund_amount <= amount),
    refund_reason VARCHAR(500),
    refunded_by BIGINT REFERENCES staff_users(id),
    refunded_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES staff_users(id),
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80) NOT NULL,
    details VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_audit_events_entity_time ON audit_events (entity_type, entity_id, created_at);
